const DISC = '#f3ead8';
const INK = '#1b1714';
const CRIMSON = '#a4161a';

/** Shift a 16x16 motif so its drawn pixels sit in the middle. */
function centre(rows) {
  let x0 = 16, x1 = -1, y0 = 16, y1 = -1;
  rows.forEach((r, y) => [...r].forEach((c, x) => {
    if (c !== '.') { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  }));
  if (x1 < 0) return rows;
  const dx = Math.floor((15 - x1 - x0) / 2);
  const dy = Math.floor((15 - y1 - y0) / 2);
  return Array.from({ length: 16 }, (_, y) => Array.from({ length: 16 }, (_, x) => rows[y - dy]?.[x - dx] ?? '.').join(''));
}

/** Compose a 32x32 crest: disc, ring, and the 16x16 motif doubled. Palette index = motif digit + 1. */
export function composeEmblem(motifRows, character) {
  const raw = Array.from({ length: 16 }, (_, y) => (motifRows[y] ?? '').padEnd(16, '.').slice(0, 16).replace(/[^.1-6]/g, '.'));
  const motif = centre(raw);
  const demon = character.pool === 'demon';
  const palette = [DISC, demon ? CRIMSON : character.palette[0], ...character.palette, INK, '#ffffff', '#d4af37'];
  const rows = [];
  for (let y = 0; y < 32; y++) {
    let row = '';
    for (let x = 0; x < 32; x++) {
      const r = Math.hypot(x - 15.5, y - 15.5);
      let px = '.';
      if (r <= 15.6) px = '0';
      const m = motif[Math.floor(y / 2)][Math.floor(x / 2)];
      if (r <= 14 && m !== '.') px = String(Number(m) + 1);
      if (r > 13.6 && r <= 15.6) px = demon && r > 14.7 ? '5' : '1';
      row += px;
    }
    rows.push(row);
  }
  return { palette, rows };
}

